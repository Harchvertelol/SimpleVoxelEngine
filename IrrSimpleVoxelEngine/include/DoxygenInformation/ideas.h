/*! \page ideas Общие идеи работы враппера IrrSimpleVoxelEngine.
 \section maininfo Общая информация
 Главной идеей движка является разбиение мира на чанки. Но как эти чанки, собственно,
 отрисовывать? Для этого производится объединение чанка в один объект, под названием
 "меш". Делается это для сокращения вызовов при отрисовке сцены. SimpleVoxelEngine
 предоставляет механизм отсечения невидимых граней, который и используется при генерации меша.
 Таким образом мир является набором мешей, которые склеиваются и обрабатываются самим
 враппером. Действия конечного пользователя при этом минимальны. На данный момент движок
 и враппер позволяют писать игры по типу cube world, minecraft, ace of spades. В общем,
 в добрый путь!
 \section meshes Как воксели превращаются в ноды Irrlicht
 -# Для каждого видимого вокселя чанка враппер вызывает функции пользовательской фабрики
 (наследника SimpleVoxelEngine::IrrEngine::FactoryChunkMeshSceneNode): getMeshVoxel() возвращает меш
 вокселя (обычно куб только из видимых граней - getMeshCubeFaces()), а getMeshNumber() - номер
 уровня, в который этот меш попадёт.
 -# Уровни нужны для разных материалов: например, уровень 0 - непрозрачные блоки, уровень 1 -
 стекло, уровень 2 - вода. У каждого уровня свой тип материала, флаги, ID нод и hardware mapping hint.
 -# Меши всех вокселей чанка склеиваются в один меш чанка (по одному на уровень).
 -# Несколько соседних чанков (блок чанков, setSizeBlockChunks()) склеиваются в одну Irrlicht-ноду
 на каждый уровень. Чем больше блок, тем меньше нод и вызовов отрисовки, но тем дольше
 перестройка при изменении одного вокселя.
 -# Когда нода блока создана или удалена, фабрика получает onUpdateChunkMeshSceneNode() - здесь
 удобно обновлять, например, селекторы треугольников для столкновений.
 \section threads Потоки
 Враппер работает в нескольких потоках:
 - <b>главный поток</b> (поток Irrlicht) вызывает IrrSimpleVoxelEngine::update(): готовые меши
 превращаются в ноды, сортируются полупрозрачные треугольники. Только здесь трогается сцена Irrlicht;
 - <b>поток главной очереди</b> по порядку выполняет задания: загрузку, генерацию и выгрузку чанков,
 установку и удаление вокселей, пользовательские функции UserControllerForThread. Пока выполняется
 одно задание, мир меняет только оно;
 - <b>потоки построения</b> (setMaxNumberOfThreadAddChunks(), setMaxNumberOfThreadUpdateChunks())
 строят меши чанков. Снимок данных чанка делается под блокировкой движка, сам меш строится без неё.
 У каждого построения есть версия: устаревший меш никогда не заменит более новый.

 Все функции IrrSimpleVoxelEngine, работающие с миром, потокобезопасны. Прямая работа с объектами
 SimpleVoxelEngine в обход враппера требует блокировки: IrrSimpleVoxelEngine::getAccessToTheSimpleVoxelEngine().
 Изменения вокселей только помечают чанки для перестройки; чтобы перестроить их, вызовите
 IrrSimpleVoxelEngine::addTaskUpdateChunks() - так тысяча изменений даёт одно построение.
 \section transparency Прозрачность
 Если материал уровня полупрозрачный (EMT_TRANSPARENT_ALPHA_CHANNEL или шейдер на его основе), враппер
 сам отключает для него запись в Z-буфер и сортирует треугольники от дальних к ближним относительно
 камеры. Для "вырезанной" прозрачности (стекло, листва, решётки) лучше подходит
 EMT_TRANSPARENT_ALPHA_CHANNEL_REF: она рисуется как непрозрачный материал и сортировки не требует.
 Чтобы сквозь прозрачные воксели были видны грани соседей, миру нужен свой
 SimpleVoxelObjectTransparentTester.
 \section proginfo Информация о программировании
 Все объекты, которые мы отдаём врапперу (фабрику, контроллер пользовательских функций, задания,
 параметры пользовательских функций, адреса и воксели в set/deleteSimpleVoxelObject()), удаляет
 сам враппер. Меш, который возвращает getMeshVoxel(), должен быть новым - враппер сам вызовет ему drop().
 Всё, что требует Irrlicht (загрузка мешей и текстур), фабрика должна загрузить в своём конструкторе:
 getMeshVoxel() вызывается в потоках построения.
*/
