/*! \page ideas Общие идеи работы движка SimpleVoxelEngine.
 \section maininfo Общая информация
 Главной идеей движка является разбиение мира на чанки, которые,
 в свою очередь, состоят из объектов "простой воксельный объект".
 А что же это такое? Это - всё что угодно. Всё, что захочет
 конечный пользователь - будет им. В частности сами чанки
 являются "простыми воксельными объектами", т.е. можно взять
 и в чанке установить не просто воксел, а ещё один чанк. А в
 нём ещё. И так далее. Получается существует возможность разбиения
 мира на любое количество объектов, при этом можно регулировать
 эти разбиения, храня воксели различными типами, в зависимости
 от необходимости. Если "кубик-воксел" повреждён, разбит - храним
 его в виде чанка. Иначе - просто отдельным кубиком. Это экономит
 и память, и процессорное время. Вложенные чанки (любой глубины и с
 любым разбиением) поддерживаются всеми функциями движка: поиск соседей
 и адресов (по сдвигу, по трём точкам, по точке), точная видимость граней,
 позиция и размер для отрисовки. Чанки верхнего уровня тоже могут быть
 разбиты по-разному (World::setMultiplePartition(false)). Флаг (движок) в руки - и в добрый путь!
 \section proginfo Информация о программировании
 Все указатели на классы, которые мы отдаём движку (воксели, генератор, контроллеры, миры),
 обрабатываются самим движком: удалять их не надо, движок сам об этом позаботится. Исключения:
 - если функция, которой отдали объект, вернула false (или -1), движок его не забрал - удаляем сами;
 - новые объекты, которые движок возвращает (адреса из getAddressSimpleVoxelObjectBy...(), список
   из getAddressesSimpleVoxelObjectsByFace(), VoxelsForRendering из getVoxelsForRenderingStatic()), удаляем сами -
   это отдельно помечено в документации.
 Отдельно стоит класс VoxelAddress: везде, где мы в функцию мира передаём на него указатель, он не удаляется -
 этим должен озаботиться конечный пользователь (сделано это для более быстрой работы алгоритмов поиска).
 Исключение - ChunkVoxelObject::setVoxelAddress(): чанк забирает адрес (это делает сам мир).
 \section userinfo Используемые понятия
 Под "вектором" какого-либо объекта мы понимаем радиус-вектор этого объекта,
 это аналогично его координатам.
*/
