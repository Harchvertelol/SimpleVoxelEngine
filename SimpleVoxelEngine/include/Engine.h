#ifndef SimpleVoxelEngine__Engine_H
#define SimpleVoxelEngine__Engine_H

#include <map>

#include "Defines.h"
#include "Logger.h"
#include "World.h"

namespace SimpleVoxelEngine
{
    namespace Core
    {
        //! Воксельный движок.
        /*! Данный класс является главным обработчиком и контроллером всего происходящего.
        */
        class Engine
        {
            public:
                //! Стандартный конструктор.
                Engine();
                //! Конструктор с логгером.
                /*! \param lgr Указатель на логгер, который будет использовать движок.
                */
                Engine(SimpleVoxelEngine::Debug::Logger* lgr);
                //! Стандартный деструктор.
                virtual ~Engine(); //Изменено: виртуальный - у движка есть виртуальная registerEvent(), наследника могут удалять через указатель на Engine.
                //! Копирование запрещено: движок владеет мирами и держит ссылку на логгер.
                Engine(const Engine&) = delete;
                //! Присваивание запрещено по той же причине.
                Engine& operator=(const Engine&) = delete;
                //! Регистрация событий.
                /*! Все сообщения движка (миров, чанков, адресов) идут через эту функцию; она передаёт их логгеру (getLogger()), если
                он установлен, а логгер выводит те типы сообщений, которые у него включены.
                Функцию можно переопределить в наследнике движка - например, чтобы дополнительно записывать сообщения в файл или
                фильтровать их по-своему. Переопределённая функция может вызвать эту (Engine::registerEvent()), чтобы сообщение
                всё равно попало в логгер. Если не переопределять, работает вывод логгера, как есть.
                \param TypeEvent Тип регистрируемого события.
                \param TextEvent Текст сообщения для логгера.
                \param IsFatal Если имеет значения true, то событие является фатальным. Рекомендуется прекратить работу с программой.
                */
                virtual void registerEvent(SimpleVoxelEngine::Defines::EventType TypeEvent, std::string TextEvent, bool IsFatal = false); //Изменено: виртуальная - вывод сообщений можно переопределить в наследнике движка.
                //! Будет ли выведено сообщение этого типа.
                /*! \param TypeEvent Тип события.
                \return Возвращает true, если логгер установлен и выводит сообщения этого типа, иначе false.
                */
                bool isEventPrinted(SimpleVoxelEngine::Defines::EventType TypeEvent) const;
                //! Создание мира по умолчанию.
                /*! Создаёт мир с параметрами по умолчанию.
                \return Возвращает идентификатор созданного мира или -1 в случае неудачи.
                */
                int addWorld();
                //! Создание мира.
                /*! Создаёт мир с указанными параметрами.
                \param wcp Параметры создания мира.
                \return Возвращает идентификатор созданного мира или -1 в случае неудачи.
                */
                int addWorld(WorldCreatingParameters& wcp);
                //! Добавление мира к движку.
                /*! Движок забирает мир и удалит его в своём деструкторе. Мир должен быть создан с этим движком (World(this, ...))
                и ещё нигде не зарегистрирован.
                \param wrld Добавляемый мир.
                \return Возвращает идентификатор добавленного мира (wrld) или -1 в случае неудачи - тогда движок мир не забирает,
                удаляет вызывающий.
                */
                int addWorld(World* wrld);
                //! Получение мира по ID.
                /*! \param id Идентификатор мира.
                \return Возвращает указатель на мир или 0 в случае неудачи.
                */
                World* getWorld(int id);
                //! Получение логгера.
                /*! После окончания работы с логгером, когда он больше не нужен, необходимо вызвать у него функцию drop(),
                чтобы уменьшить число ссылок на него.
                \return Возвращает указатель на логгер, установленный движку или 0 в случае, если его нет.
                */
                SimpleVoxelEngine::Debug::Logger* getLogger();
            private:
                SimpleVoxelEngine::Debug::Logger* s_Logger;
                std::map< int, World* > s_Worlds;
                int s_NumberWorlds;
        };
    }
}

#endif
